"""The HTTP API.

    uv run uvicorn sillage.interfaces.api.app:app            # local
    docker run -p 8000:8000 sillage                          # container

Endpoints:

- ``POST /predict`` -- SMILES in, odour report out. **A refusal is HTTP 422** with a
  stable ``reason`` code, the same body shape whether the input failed schema
  validation or fell outside the model's scope. A caller handles one error format.
- ``GET /model`` -- what model answers, its scope, metrics and their floor.
- ``GET /health`` -- liveness, for the container healthcheck.
- ``GET /metrics`` -- Prometheus exposition.
- ``GET /docs`` -- interactive documentation, generated by FastAPI.

The model loads once, at startup. A missing or unreadable artifact fails the start
loudly instead of serving 500s on every request later.
"""

from __future__ import annotations

import time
from collections.abc import AsyncIterator, Awaitable, Callable
from contextlib import asynccontextmanager

from fastapi import FastAPI, Request, Response
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from prometheus_client import CONTENT_TYPE_LATEST, generate_latest

from sillage import __version__
from sillage.application import PredictOdor
from sillage.domain import Refusal
from sillage.interfaces.api.metrics import ServiceMetrics
from sillage.interfaces.api.schemas import (
    ModelOut,
    PredictRequest,
    RefusalOut,
    ReportOut,
    model_out,
    refusal_out,
    report_out,
)

REFUSAL_STATUS = 422


def create_app(load: Callable[[], PredictOdor] | None = None) -> FastAPI:
    """Build the app. *load* is called once at startup; tests pass their own."""

    @asynccontextmanager
    async def lifespan(app: FastAPI) -> AsyncIterator[None]:
        if load is None:
            from sillage.interfaces.composition import build_predict_odor

            predict = build_predict_odor()
        else:
            predict = load()
        app.state.predict = predict
        app.state.metrics = ServiceMetrics(predict.predictor.name)
        yield

    app = FastAPI(
        title="sillage",
        version=__version__,
        summary="Predicts what a molecule smells of, and says how sure it is.",
        lifespan=lifespan,
    )

    @app.middleware("http")
    async def record(request: Request, call_next: Callable[[Request], Awaitable[Response]]):
        started = time.perf_counter()
        response = await call_next(request)
        metrics: ServiceMetrics | None = getattr(request.app.state, "metrics", None)
        if metrics is not None:
            # The route *template*, never the raw path: a label per distinct URL is
            # unbounded cardinality and eventually takes Prometheus down.
            route = request.scope.get("route")
            template = getattr(route, "path", "unmatched")
            metrics.http_requests.labels(request.method, template, str(response.status_code)).inc()
            metrics.http_latency.labels(template).observe(time.perf_counter() - started)
        return response

    @app.exception_handler(RequestValidationError)
    async def invalid_request(request: Request, error: RequestValidationError) -> JSONResponse:
        problems = "; ".join(
            f"{'.'.join(str(p) for p in e['loc'] if p != 'body')}: {e['msg']}"
            for e in error.errors()
        )
        body = RefusalOut(reason="invalid_input", detail=problems or "invalid request")
        metrics: ServiceMetrics | None = getattr(request.app.state, "metrics", None)
        if metrics is not None and request.url.path == "/predict":
            metrics.predictions.labels(outcome="refused").inc()
            metrics.refusals.labels(reason="invalid_input").inc()
        return JSONResponse(body.model_dump(), status_code=REFUSAL_STATUS)

    @app.post(
        "/predict",
        response_model=ReportOut,
        responses={REFUSAL_STATUS: {"model": RefusalOut, "description": "Refused, with reason"}},
    )
    def predict(body: PredictRequest, request: Request) -> ReportOut | JSONResponse:
        # A plain `def`: prediction is CPU-bound, and FastAPI runs sync handlers in a
        # thread pool instead of blocking the event loop that serves other requests.
        started = time.perf_counter()
        result = request.app.state.predict(body.smiles, neighbours=body.neighbours)
        request.app.state.metrics.observe(result, time.perf_counter() - started)

        if isinstance(result, Refusal):
            return JSONResponse(refusal_out(result).model_dump(), status_code=REFUSAL_STATUS)
        return report_out(result)

    @app.get("/model", response_model=ModelOut)
    def model(request: Request) -> ModelOut:
        return model_out(request.app.state.predict.predictor.describe())

    @app.get("/health")
    def health(request: Request) -> dict[str, str]:
        return {"status": "ok", "model": request.app.state.predict.predictor.name}

    @app.get("/metrics", include_in_schema=False)
    def metrics(request: Request) -> Response:
        return Response(
            generate_latest(request.app.state.metrics.registry), media_type=CONTENT_TYPE_LATEST
        )

    return app


app = create_app()
